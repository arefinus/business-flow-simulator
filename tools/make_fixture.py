"""Generate the committed synthetic fixture: the baseline workload at seed 42.

Usage: python tools/make_fixture.py [--seed 42] [--out examples/fixtures/v1]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from business_flow_simulator.outputs import canonical_json, sha256_bytes, write_json, write_text  # noqa: E402
from business_flow_simulator.scenario import load_scenario  # noqa: E402
from business_flow_simulator.workload import generate_workload  # noqa: E402

FIXTURE_TEXT = """# Fixture v1

Authored synthetic demonstration data. Fictional identifiers. Not derived from any
person, company, account or dataset. Generated by `tools/make_fixture.py` seed {seed},
version v1.

* `workload_baseline.json`: the materialised baseline workload ({orders} purchase orders,
  {skus} SKUs, {customers} fictional customer accounts) that `make smoke` runs on. Every
  fault draw is fixed in the file, so the three policies see identical input.
* Money is integer cents of a fictional USD scenario. Company names are obviously
  fictional ("Northwind Demo Supply", "Blue Harbor Demo Retail").
* sha256 of `workload_baseline.json` (canonical JSON of the workload): `{digest}`

Regenerate with `python tools/make_fixture.py`. The file is byte-identical on every run.
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", default=str(ROOT / "examples" / "fixtures" / "v1"))
    args = parser.parse_args()
    scenario = load_scenario("baseline").with_seed(args.seed)
    workload = generate_workload(scenario)
    data = workload.to_dict()
    out = Path(args.out)
    write_json(out / "workload_baseline.json", data)
    digest = sha256_bytes(canonical_json(data).encode("utf-8"))
    write_text(out / "FIXTURE.md", FIXTURE_TEXT.format(
        seed=args.seed, orders=len(workload.orders), skus=len(workload.skus),
        customers=len(workload.customers), digest=digest))
    print(f"wrote {out / 'workload_baseline.json'} ({len(workload.orders)} orders), sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
